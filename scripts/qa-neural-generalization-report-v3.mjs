#!/usr/bin/env node
import { privateValue } from "../lib/server/private-ledger.mjs";
// Bounded synthetic local-file QA; profile/cache/downloads/screenshots stay NAS.
import {createRequire} from 'node:module';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {gunzipSync} from 'node:zlib';
import assert from 'node:assert/strict';
const args=new Map();for(let i=2;i<process.argv.length;i+=2)args.set(process.argv[i],process.argv[i+1]);
for(const key of ['--harness','--html','--source-json','--output-root'])assert.ok(args.has(key),key+' required');
const out=resolve(args.get('--output-root'));
assert.ok(new RegExp(privateValue("private-reference-0107"), "i").test(out),'NAS output required');
process.env.TEMP=join(out,'temp');process.env.TMP=process.env.TEMP;
await mkdir(process.env.TEMP,{recursive:true});
const require=createRequire(join(resolve(args.get('--harness')),'package.json'));
const {chromium}=require('playwright-core');
const browser=await chromium.launch({executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',headless:true,args:['--disable-gpu','--disk-cache-dir='+join(out,'cache')]});
const context=await browser.newContext({viewport:{width:1440,height:1100},acceptDownloads:true});
const page=await context.newPage(),errors=[],requests=[],checks={};
page.on('pageerror',e=>errors.push(String(e)));page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url())});
try{
 await page.goto(pathToFileURL(resolve(args.get('--html'))).href);await page.waitForFunction(()=>!!window.__reportQA);
 assert.equal(await page.evaluate(()=>window.__reportQA.presentationVersion),3);
 assert.equal(await page.locator('#fixtureWarning').isVisible(),true);
 assert.match(await page.locator('label[for=filter-model]').textContent(),/Model/);
 assert.equal(await page.locator('#filter-model').inputValue(),'*');
 await page.selectOption('#filter-model','av-tcn');
 assert.equal(await page.evaluate(()=>window.__reportQA.activeRows().filter(r=>r.variant!=='fixed-production').every(r=>r.model==='av-tcn')),true);
 checks.modelFilter=true;
 await page.selectOption('#comparisonMode','variants');
 assert.equal(await page.locator('#filter-panel').inputValue(),'common-unseen');
 assert.equal(await page.locator('#filter-scenario').isDisabled(),true);
 for(const id of ['model','draw','dtype'])assert.equal(await page.locator('#filter-'+id+' option[value="*"]').isDisabled(),true);
 const snapshot=await page.evaluate(()=>({rows:window.__reportQA.activeRows().length,variants:window.__reportQA.selectedVariants(),groups:window.__reportQA.visibleGroups(),complete:window.__reportQA.completeCount()}));
 assert.equal(snapshot.variants.length,6);assert.equal(snapshot.rows,77);assert.equal(snapshot.groups,7);assert.equal(snapshot.complete,76);
 assert.match(await page.locator('#comparisonWarning').textContent(),/Same recording scope/);
 assert.equal(await page.locator('#legend button').filter({hasText:'production-unmatched'}).count(),0);
 checks.matchedSixVariants=snapshot;
 await page.selectOption('#tableFloor','100');
 assert.equal(await page.locator('#results tbody tr').count(),7);assert.equal(await page.locator('#results tbody tr.infeasible').count(),1);
 assert.equal((await page.locator('#results tbody tr.infeasible').locator('td').nth(3).textContent()).trim(),'—');
 checks.incompleteMeanIsGap=true;
 await page.selectOption('#filter-panel','task-unseen-sources');
 assert.match(await page.locator('#comparisonWarning').textContent(),/SOURCE SCOPE MISMATCH/);
 assert.equal(await page.locator('#scopeWarning').isVisible(),true);
 await page.locator('#variantChoices input[value="expanded-wide-validation"]').uncheck();
 assert.match(await page.locator('#comparisonWarning').textContent(),/Same recording scope/);
 assert.equal(await page.evaluate(()=>window.__reportQA.visibleGroups()),6);
 checks.scopeMismatchAndCheckbox=true;
 await page.locator('#variantChoices input[value="expanded-wide-validation"]').check();
 await page.selectOption('#filter-panel','common-unseen');await page.selectOption('#filter-model','dino-tcn');await page.selectOption('#filter-policy','reviewed-export');
 assert.match(await page.locator('#comparisonWarning').textContent(),/No saved rows in this view for: export-rally-selection/);
 assert.match(await page.locator('#scenarioWarning').textContent(),/for calibration alongside exact gold/);
 assert.equal(await page.evaluate(()=>window.__reportQA.activeRows().some(r=>r.variant==='export-rally-selection')),false);
 checks.absentVariantNotFabricated=true;
 await page.selectOption('#filter-model','av-tcn');await page.selectOption('#filter-policy','exact-rallies');await page.selectOption('#tableFloor','*');
 await page.screenshot({path:join(out,'variants-desktop.png'),fullPage:true});
 await page.selectOption('#comparisonMode','models');await page.selectOption('#filter-scenario','historical-nested');await page.selectOption('#filter-draw','3407');
 assert.match(await page.locator('#contextWarning').textContent(),/cannot be attributed to model or training changes alone/);
 assert.equal(await page.locator('#variantControls').isVisible(),false);
 assert.equal(await page.evaluate(()=>window.__reportQA.activeRows().filter(r=>r.variant!=='fixed-production').every(r=>r.variant==='historical-nested')),true);
 checks.historicalSeparate=true;
 const pending=page.waitForEvent('download');await page.click('#download');const download=await pending;const downloaded=join(out,'exact-source.json.gz');await download.saveAs(downloaded);
 const raw=await readFile(args.get('--source-json'));assert.deepEqual(gunzipSync(await readFile(downloaded)),raw);checks.exactSourceSha256=createHash('sha256').update(raw).digest('hex');
 assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
 checks.savedRows=await page.evaluate(()=>window.__reportQA.sourceRows);checks.materializedAcrossInteractions=await page.evaluate(()=>window.__reportQA.materializedRows());
 await writeFile(join(out,'qa.json'),JSON.stringify({kind:'synthetic-matched-variant-ui-qa-v3',passed:true,syntheticOnly:true,checks,errors,externalRequests:requests,profileAndTempRoot:process.env.TEMP},null,2)+'\n');
 console.log(JSON.stringify({passed:true,checks}));
}finally{await context.close();await browser.close()}
