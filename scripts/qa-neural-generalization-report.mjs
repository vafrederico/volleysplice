#!/usr/bin/env node
// Local standalone HTML QA. No production server and no external page requests.
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i], process.argv[i + 1]);
for (const key of ['--harness', '--html', '--output-root']) if (!args.has(key)) throw new Error(`${key} required`);
const output = resolve(args.get('--output-root'));
process.env.TEMP = join(output, 'temp');
process.env.TMP = process.env.TEMP;
const require = createRequire(join(resolve(args.get('--harness')), 'package.json'));
const { chromium } = require('playwright-core');
const html = resolve(args.get('--html'));
const browser = await chromium.launch({executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true, args: ['--disable-gpu']});
const context = await browser.newContext({viewport: {width: 1440, height: 1060}, acceptDownloads: true});
const page = await context.newPage();
const errors = [], externalRequests = [];
page.on('pageerror', error => errors.push(String(error)));
page.on('request', request => { if (/^https?:/.test(request.url())) externalRequests.push(request.url()); });
const checks = {};
try {
  await page.goto(pathToFileURL(html).href);
  await page.waitForFunction(() => !!window.__reportQA);
  checks.fixtureMarked = await page.locator('#fixtureWarning').isVisible();
  assert.equal(checks.fixtureMarked, true, 'fixture must be visibly marked');
  assert.equal(await page.evaluate(() => window.INJECTED), undefined, 'embedded JSON must not execute HTML');
  checks.initial = await page.evaluate(() => ({filtered: window.__reportQA.filteredCount(), complete: window.__reportQA.completeCount(), groups: window.__reportQA.visibleGroups()}));
  assert.deepEqual(checks.initial, {filtered: 44, complete: 40, groups: 4});
  assert.equal(await page.locator('#precisionChart circle').count(), 40, 'infeasible points must have no fabricated metric circle');
  assert.equal(await page.locator('#precisionChart text').filter({hasText: '×'}).count(), 4, 'infeasible gaps must remain visible');
  assert.match(await page.locator('#productionNotice').textContent(), /not recalibrated/);
  assert.equal(await page.locator('#legend button').filter({hasText: 'production-unmatched'}).count(), 0);
  await page.uncheck('#showProduction');
  assert.equal(await page.evaluate(() => window.__reportQA.filteredCount()), 33);
  await page.check('#showProduction');
  assert.equal(await page.evaluate(() => window.__reportQA.filteredCount()), 44);
  checks.productionOverlayOnlyMatchedScope = true;
  assert.match(await page.locator('#contextWarning').textContent(), /full-timeline inference with labels hidden/);
  await page.selectOption('#filter-scenario', 'historical-nested');
  assert.match(await page.locator('#contextWarning').textContent(), /cannot be attributed to model or training changes alone/);
  assert.match(await page.locator('#contextWarning').getAttribute('class'), /error/);
  await page.selectOption('#filter-scenario', 'baseline');
  checks.historicalContextDistinguished = true;
  await page.screenshot({path: join(output, 'desktop.png'), fullPage: true});
  await page.selectOption('#tableFloor', '100');
  assert.equal(await page.locator('#results tbody tr').count(), 4);
  assert.equal(await page.locator('#results tbody tr.infeasible').count(), 3);
  assert.equal(await page.locator('#results tbody tr').first().locator('td').nth(3).textContent(), '—');
  checks.infeasible100NotZero = true;
  await page.selectOption('#tableFloor', '*');
  await page.locator('#legend button').first().click();
  assert.equal(await page.evaluate(() => window.__reportQA.visibleGroups()), 3);
  checks.lineToggle = true;
  await page.selectOption('#filter-policy', 'reviewed-export');
  assert.match(await page.locator('#labelWarning').textContent(), /do not certify precise rally separation/);
  assert.equal(await page.locator('#f1ChartTitle').textContent(), 'Coverage F1');
  checks.coverageContractVisible = true;
  await page.selectOption('#filter-policy', 'reviewed-draft');
  assert.equal(await page.locator('#f1ChartTitle').textContent(), 'F1_reviewed');
  checks.draftMetricName = true;
  await page.selectOption('#filter-policy', 'reviewed-export');
  await page.selectOption('#filter-scenario', 'export-rally-training');
  await page.selectOption('#filter-padding', '3');
  checks.variantFilters = await page.evaluate(() => window.__reportQA.filteredCount());
  assert.equal(checks.variantFilters, 44);
  await page.fill('#videoSearch', 'group-D');
  assert.equal(await page.locator('#inventory tbody tr').count(), 1);
  assert.match(await page.locator('#inventory tbody tr').textContent(), /Unknown lineage/);
  assert.equal(await page.evaluate(() => window.INJECTED), undefined);
  checks.inventoryFilterAndEscaping = true;
  await page.fill('#videoSearch', '');
  const downloadPromise = page.waitForEvent('download');
  await page.click('#download');
  const download = await downloadPromise;
  const saved = join(output, 'downloaded-fixture.json');
  await download.saveAs(saved);
  const decoded = JSON.parse(await readFile(saved, 'utf8'));
  assert.equal(decoded.metadata.syntheticFixture, true);
  assert.equal(decoded.series.length, await page.evaluate(() => window.__reportQA.sourceRows));
  assert.ok(decoded.scopes && decoded.series.every(row => row.scopeId && !row.recordingIds));
  assert.ok(decoded.series.some(row => row.status === 'available'));
  assert.equal(await page.locator('#results tbody tr').first().locator('td').last().textContent(), '2');
  checks.compactScopesAndAvailableStatus = true;
  checks.jsonDownloadComplete = true;
  await page.setViewportSize({width: 390, height: 844});
  await page.selectOption('#filter-scenario', 'baseline');
  await page.selectOption('#filter-policy', 'exact-core');
  await page.selectOption('#filter-padding', '2');
  const dimensions = await page.evaluate(() => ({scroll: document.documentElement.scrollWidth, viewport: innerWidth}));
  assert.ok(dimensions.scroll <= dimensions.viewport + 1, `mobile horizontal overflow: ${JSON.stringify(dimensions)}`);
  await page.screenshot({path: join(output, 'mobile.png'), fullPage: true});
  checks.mobileViewport = dimensions;
  assert.deepEqual(errors, []);
  assert.deepEqual(externalRequests, []);
  checks.noPageErrorsOrExternalRequests = true;
  const sha = bytes => createHash('sha256').update(bytes).digest('hex');
  const report = {kind: 'neural-generalization-html-synthetic-qa-v1', passed: true, syntheticFixtureOnly: true,
    html: {path: html, sha256: sha(await readFile(html))}, scriptSha256: sha(await readFile(fileURLToPath(import.meta.url))),
    checks, errors, externalRequests, browser: await browser.version()};
  await writeFile(join(output, 'browser-qa.json'), JSON.stringify(report, null, 2) + '\n', {flag: 'wx'});
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
