import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { privateValue } from "../lib/server/private-ledger.mjs";

const args = new Map(process.argv.slice(2).reduce((rows, v, i, all) => i % 2 ? rows : [...rows, [v, all[i + 1]]], []));
if (!args.get("--output") || !args.get("--browser")) throw Error("Specify external --output and --browser");
const require = createRequire(path.resolve(args.get("--harness") ?? privateValue("private-reference-0109"), "package.json"));
const { chromium } = require("playwright-core");
const browser = await chromium.launch({ executablePath: args.get("--browser"), headless: true });
const context = await browser.newContext({ viewport: { width: 1500, height: 1100 }, reducedMotion: "reduce" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
const baseUrl = args.get("--url") ?? "http://localhost:3000";
const target = new URL(privateValue("private-reference-0115"), baseUrl);
target.searchParams.set("mode", "neural-mobile-tcn-fp32-high-recall");
const drafts = () => page.evaluate(() => Object.entries(localStorage).filter(([k]) => k.includes(":trial:v1:")).map(([key, value]) => ({ key, draft: JSON.parse(value) })));
const checks = [];
try {
  await page.goto(target.href, { waitUntil: "networkidle", timeout: 90000 });
  const selector = page.getByLabel("Suppression combination", { exact: true });
  await selector.waitFor();
  await page.getByTestId("lab-comparison-metrics").waitFor();
  await selector.selectOption("aggressive");
  await page.getByTestId("suppression-baseline-comparison").waitFor();
  await page.getByRole("button", { name: "Restore footage", exact: true }).waitFor();
  const metrics = await page.getByTestId("lab-comparison-metrics").innerText();
  await page.getByRole("button", { name: "Restore footage", exact: true }).click();
  await page.waitForFunction(() => Object.entries(localStorage).some(([k, v]) => k.includes(":trial:v1:") && k.endsWith("--suppression-aggressive") && Object.values(JSON.parse(v).suppressionDecisionOverrides ?? {}).includes("keep")));
  const restoredMetrics = await page.getByTestId("lab-comparison-metrics").innerText();
  assert.notEqual(restoredMetrics, metrics);
  await page.keyboard.press("Control+z");
  await page.waitForFunction(() => Object.entries(localStorage).some(([k, v]) => k.includes(":trial:v1:") && k.endsWith("--suppression-aggressive") && Object.keys(JSON.parse(v).suppressionDecisionOverrides ?? {}).length === 0));
  assert.equal(await page.getByTestId("lab-comparison-metrics").innerText(), metrics);
  checks.push("Restoring a suppressed rally updates the live export metrics; Undo reverses both.");
  await selector.selectOption("direct");
  await page.getByTestId("suppression-baseline-comparison").waitFor();
  assert.match(await page.locator("body").innerText(), /no production agreement protection/);
  await selector.selectOption("none");
  assert.equal(await page.getByTestId("suppression-baseline-comparison").count(), 0);
  const values = await drafts();
  assert.ok(values.some(v => v.key.endsWith(":neural-mobile-tcn-fp32-high-recall")));
  assert.ok(values.some(v => v.key.endsWith("--suppression-direct")));
  assert.ok(values.some(v => v.key.endsWith("--suppression-aggressive")));
  checks.push("Off, production-gated and head-only experiments have independent drafts.");
  const group = page.getByRole("group", { name: "Model configuration", exact: true });
  const buttons = await group.getByRole("button").all();
  let models = 0;
  for (const button of buttons) {
    const label = await button.innerText();
    if (!/TCN|transformer|Compact standalone/.test(label)) continue;
    await button.click(); await selector.selectOption("conservative");
    await page.getByTestId("suppression-baseline-comparison").waitFor();
    models++;
  }
  assert.ok(models >= 11);
  checks.push(`${models} standalone neural model options support suppression combinations.`);
  await group.getByRole("button", { name: "Production ensemble", exact: true }).click();
  assert.equal(await selector.locator('option[value="direct"]').count(), 0);
  await group.getByRole("button", { name: "Human export", exact: true }).click();
  assert.equal(await selector.isDisabled(), true);
  checks.push("Production retains the agreement gate; saved human export cannot be suppressed.");
  await group.getByRole("button", { name: /^Mobile-TCN .*highest F1/ }).click();
  await selector.selectOption("aggressive");
  await page.reload({ waitUntil: "networkidle" });
  assert.equal(await selector.inputValue(), "aggressive");
  await page.getByTestId("suppression-baseline-comparison").waitFor();
  await mkdir(args.get("--output"), { recursive: true });
  await page.screenshot({ path: path.join(args.get("--output"), "suppression-comparison.png"), fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile(path.join(args.get("--output"), "browser-checks.json"), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }));
} finally { await context.close(); await browser.close(); }
